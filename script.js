const eraTabs = [...document.querySelectorAll(".era-tab")];
const eraDetail = document.querySelector("#era-detail");

function selectEra(tab) {
  const release = releaseDetails[tab.dataset.era];
  if (!release) return;

  eraTabs.forEach((item) => {
    const active = item === tab;
    item.classList.toggle("is-active", active);
    item.setAttribute("aria-selected", String(active));
    item.tabIndex = active ? 0 : -1;
  });

  eraDetail.setAttribute("aria-labelledby", tab.id);
  eraDetail.querySelector(".era-detail-date strong").textContent = release.date;
  eraDetail.querySelector(".era-detail-date > span:last-child").textContent = release.year;
  eraDetail.querySelector(".era-detail-kicker").textContent = release.kicker;
  eraDetail.querySelector("h4").textContent = release.title;
  eraDetail.querySelector(".era-detail-copy > p:not(.era-detail-kicker, .era-design-note)").textContent =
    release.description;
  eraDetail.querySelector(".era-design-note").lastChild.textContent = ` ${release.question}`;
  eraDetail.querySelector(".era-detail-index").textContent = release.number;

  eraDetail.classList.remove("is-changing");
  void eraDetail.offsetWidth;
  eraDetail.classList.add("is-changing");
}

eraTabs.forEach((tab, index) => {
  tab.addEventListener("click", () => selectEra(tab));
  tab.addEventListener("keydown", (event) => {
    let nextIndex;
    if (event.key === "ArrowRight") nextIndex = (index + 1) % eraTabs.length;
    if (event.key === "ArrowLeft") nextIndex = (index - 1 + eraTabs.length) % eraTabs.length;
    if (event.key === "Home") nextIndex = 0;
    if (event.key === "End") nextIndex = eraTabs.length - 1;
    if (nextIndex === undefined) return;

    event.preventDefault();
    eraTabs[nextIndex].focus();
    selectEra(eraTabs[nextIndex]);
  });
});

if ("IntersectionObserver" in window) {
  const revealObserver = new IntersectionObserver(
    (entries, observer) => {
      entries.forEach((entry) => {
        if (!entry.isIntersecting) return;
        entry.target.classList.add("is-visible");
        observer.unobserve(entry.target);
      });
    },
    { threshold: 0.12, rootMargin: "0px 0px -24px 0px" },
  );
  const revealItems = [...document.querySelectorAll("[data-reveal]")];

  if (!window.matchMedia("(prefers-reduced-motion: reduce)").matches) {
    document.documentElement.classList.add("motion-ready");
  }
  revealItems.forEach((item) => revealObserver.observe(item));

  const sectionLinks = [...document.querySelectorAll(".navigation a[href^='#']")];
  const sectionObserver = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (!entry.isIntersecting) return;
        sectionLinks.forEach((link) => {
          const active = link.hash === `#${entry.target.id}`;
          if (active) link.setAttribute("aria-current", "location");
          else link.removeAttribute("aria-current");
        });
      });
    },
    { rootMargin: "-25% 0px -65% 0px" },
  );
  sectionLinks.forEach((link) => {
    const section = document.querySelector(link.hash);
    if (section) sectionObserver.observe(section);
  });
}

const heroArt = document.querySelector(".hero-art");
if (
  window.matchMedia("(hover: hover) and (pointer: fine)").matches &&
  !window.matchMedia("(prefers-reduced-motion: reduce)").matches
) {
  let pointerFrame = 0;
  let pointerX = 0;
  let pointerY = 0;

  window.addEventListener(
    "pointermove",
    (event) => {
      pointerX = event.clientX;
      pointerY = event.clientY;
      if (pointerFrame) return;

      pointerFrame = window.requestAnimationFrame(() => {
        document.documentElement.style.setProperty("--pointer-x", `${pointerX}px`);
        document.documentElement.style.setProperty("--pointer-y", `${pointerY}px`);
        document.documentElement.classList.add("ambient-ready");
        pointerFrame = 0;
      });
    },
    { passive: true },
  );
  window.addEventListener("pointerleave", () => {
    document.documentElement.classList.remove("ambient-ready");
  });

  heroArt.addEventListener("pointermove", (event) => {
    const bounds = heroArt.getBoundingClientRect();
    const x = ((event.clientX - bounds.left) / bounds.width) * 100;
    const y = ((event.clientY - bounds.top) / bounds.height) * 100;
    heroArt.style.setProperty("--pointer-x", `${x}%`);
    heroArt.style.setProperty("--pointer-y", `${y}%`);
  });
  heroArt.addEventListener("pointerleave", () => {
    heroArt.style.removeProperty("--pointer-x");
    heroArt.style.removeProperty("--pointer-y");
  });
}

